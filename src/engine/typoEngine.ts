/**
 * Returns a plausible slip / typo character for a given Chinese or Latin character.
 * GUARANTEES that the returned typo is DIFFERENT from char.
 * If no realistic typo is known, returns null.
 */
export function getTypoForChar(char: string, randomFn: () => number = Math.random): string | null {
  // 1. Check high-frequency phonetic typos
  const phonetic = HIGH_FREQUENCY_TYPOS[char];
  if (phonetic && phonetic.length > 0) {
    const valid = phonetic.filter(c => c !== char);
    if (valid.length > 0) {
      return valid[Math.floor(randomFn() * valid.length)];
    }
  }

  // 2. Check visual shape confusions (Chinese)
  const visual = VISUAL_CONFUSIONS[char];
  if (visual && visual.length > 0) {
    const valid = visual.filter(c => c !== char);
    if (valid.length > 0) {
      return valid[Math.floor(randomFn() * valid.length)];
    }
  }

  // 3. Check Latin letters & digits confusions
  const latin = LATIN_CONFUSIONS[char];
  if (latin && latin.length > 0) {
    const valid = latin.filter(c => c !== char);
    if (valid.length > 0) {
      return valid[Math.floor(randomFn() * valid.length)];
    }
  }

  // 4. Fallback for unmapped Chinese characters: return a credible slip character that is guaranteed !== char
  const code = char.charCodeAt(0);
  if (code >= 0x4e00 && code <= 0x9fa5) {
    const GENERIC_SLIPS = ['之', '已', '末', '目', '各', '同', '于', '也', '自', '反', '入', '士'];
    const valid = GENERIC_SLIPS.filter(c => c !== char);
    return valid[Math.floor(randomFn() * valid.length)];
  }

  // 5. Fallback for unmapped Latin letters and digits
  if (/[a-z]/.test(char)) {
    const GENERIC_LATIN_LOWER = ['e', 'a', 'o', 'n', 't', 's'];
    const valid = GENERIC_LATIN_LOWER.filter(c => c !== char);
    return valid[Math.floor(randomFn() * valid.length)];
  }
  if (/[A-Z]/.test(char)) {
    const GENERIC_LATIN_UPPER = ['A', 'E', 'O', 'T', 'N', 'S'];
    const valid = GENERIC_LATIN_UPPER.filter(c => c !== char);
    return valid[Math.floor(randomFn() * valid.length)];
  }
  if (/[0-9]/.test(char)) {
    const GENERIC_DIGITS = ['0', '1', '2', '3', '5', '8'];
    const valid = GENERIC_DIGITS.filter(c => c !== char);
    return valid[Math.floor(randomFn() * valid.length)];
  }

  return null;
}

/**
 * Checks if a character has a known credible slip / typo variant.
 */
export function hasTypoVariant(char: string): boolean {
  return (
    (HIGH_FREQUENCY_TYPOS[char]?.length ?? 0) > 0 ||
    (VISUAL_CONFUSIONS[char]?.length ?? 0) > 0 ||
    (LATIN_CONFUSIONS[char]?.length ?? 0) > 0 ||
    (char.charCodeAt(0) >= 0x4e00 && char.charCodeAt(0) <= 0x9fa5) ||
    /[a-zA-Z0-9]/.test(char)
  );
}
